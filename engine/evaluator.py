def evaluate_board(board: chess.Board) -> int:
    """Computes a static material and positional score from White's perspective.

    Positive score indicates advantage for White; negative indicates Black advantage.
    """
    if board.is_checkmate():
        return -99999 if board.turn == chess.WHITE else 99999

    if board.is_stalemate() or board.is_insufficient_material() or board.can_claim_draw():
        return 0

    score: int = 0
    for piece_type, value in PIECE_VALUES.items():
        pst: list[int] = PIECE_PST[piece_type]

        # White pieces: direct square lookup
        for square in board.pieces(piece_type, chess.WHITE):
            score += value + pst[square]

        # Black pieces: mirrored square lookup
        for square in board.pieces(piece_type, chess.BLACK):
            score -= value + pst[chess.square_mirror(square)]

    return score
